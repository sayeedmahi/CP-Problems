void solve() {
    int n; cin>>n;
    vll a(n), b(n); for (ll &x:a) cin>>x;
    b=a;
    ll ls=a[0], ss=a[0], ans=a[0];
    for (int i=1; i<n; i++) {
        ans=max(ans, a[i]+max(ls, -ss));
        ls=a[i]+max(0LL, 2*ls);
        ss=a[i]+min(0LL, 2*ss);
    } cout << ans << endl;
}

